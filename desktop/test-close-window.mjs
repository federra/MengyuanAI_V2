import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {once} from 'node:events';
const require=createRequire(import.meta.url);
const {app,BrowserWindow}=require('electron');
const {attachCloseGuard}=require('./close-window.cjs');
const {createShutdown}=require('./shutdown.cjs');
app.setName('Director close lifecycle isolated test');
app.setPath('userData',fs.mkdtempSync(path.join(os.tmpdir(),'director-close-')));
const log=async message=>console.log(message);let prompts=0,helperStops=0,stage=0;
const shutdown=createShutdown({getBackend:()=>null,stopHelper:async()=>{helperStops++;},log,exit:()=>{assert.equal(helperStops,1);console.log('PASS LIVE Electron: dirty window close and menu quit can be cancelled without stopping services; confirmed close shuts down once.');app.exit(0);}});
app.on('window-all-closed',()=>app.quit());
app.on('will-quit',event=>{event.preventDefault();assert.equal(stage,3);void shutdown();});
setTimeout(()=>{console.error(`Close lifecycle test timed out stage=${stage} prompts=${prompts}`);app.exit(1);},15000).unref();
void app.whenReady().then(async()=>{try {
  console.log('Electron test ready.');
  const win=new BrowserWindow({show:false,webPreferences:{nodeIntegration:false,contextIsolation:true,sandbox:true}});
  attachCloseGuard(win,{log,dialog:{showMessageBoxSync:()=>++prompts===3?1:0}});
  await win.loadURL('data:text/html,<h1>Isolated close test</h1>');
  await win.webContents.executeJavaScript("window.addEventListener('beforeunload', e => { e.preventDefault(); e.returnValue = ''; });",true);
  let blocked=once(win.webContents,'will-prevent-unload');win.close();await blocked;
  stage=1;assert(!win.isDestroyed());assert.equal(helperStops,0);
  await new Promise(resolve=>setTimeout(resolve,100));
  blocked=once(win.webContents,'will-prevent-unload');app.quit();await blocked;
  stage=2;assert(!win.isDestroyed());assert.equal(helperStops,0);
  await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(prompts,2);stage=3;win.close();
} catch(error){console.error(error);app.exit(1);}});
