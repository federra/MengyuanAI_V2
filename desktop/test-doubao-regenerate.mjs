import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {createRequire} from 'node:module';
const {DoubaoManager}=createRequire(import.meta.url)('./doubao-manager.cjs');
const root=await fs.mkdtemp(path.join(os.tmpdir(),'director-regenerate-'));
let opens=0;
const m=await new DoubaoManager({root,backend:()=>({}),launch:async()=>{opens++;}}).start();
try {
  await m.command('account',{name:'test',group:'A'});
  const a=m.state.accounts[0];
  await m.command('participation',{ids:[a.id],selected:true});
  const bundle={format:'director-doubao-task',version:1,projectId:'p',tasks:[{id:'shot',title:'镜头1',prompt:'原对白',references:[{mediaId:'image1',label:'图1'},{mediaId:'image2',label:'图2'}]}],media:[{id:'image1'},{id:'image2'}]};
  await m.command('enqueue',{bundle,accountIds:[a.id]});
  const old=m.state.jobs[0];
  Object.assign(old,{status:'prepared',accountId:a.id});
  await m.event(a,{type:'workflow',jobId:old.id,error:'video mode failed'});
  await m.event(a,{type:'runtime',state:'idle',readyForGeneration:true});
  assert.equal(old.error,'video mode failed','idle heartbeat preserves workflow failure');
  await m.event(a,{type:'workflow',jobId:old.id,error:'',steps:['video mode ready']});
  assert.equal(old.error,'');
  Object.assign(old,{status:'attention',history:[{message:'未确认已切换到视频模式'}],retryJobId:'cancelled-retry'});
  Object.assign(a,{runtimeState:'idle',idleSamples:2,runtimeAt:Date.now()});
  old.submissionAttemptedAt=Date.now();
  assert.equal((await m.event(a,{type:'preparationAbandoned',jobId:old.id,noSubmissionAttempt:true})).released,false,'submission intent blocks preflight abandonment');
  delete old.submissionAttemptedAt;
  assert.equal((await m.event(a,{type:'preparationAbandoned',jobId:old.id,noSubmissionAttempt:true})).released,true,'proven preflight failure releases an old cancelled retry lock');
  assert.equal(old.status,'failed');delete old.retryJobId;delete old.terminalAt;
  old.status='prepared';await m.event(a,{type:'submissionIntent',jobId:old.id});
  await assert.rejects(m.event(a,{type:'submissionIntent',jobId:old.id}),/已尝试提交/);
  Object.assign(old,{status:'submitted',accountId:a.id,submittedAt:new Date().toISOString(),waitStartedAt:Date.now()-21*60000,requestId:'request'});
  await m.expire();assert.equal(old.status,'attention');assert.match(old.error,/尚未确认结果/);
  const beforePreview=JSON.stringify(m.state), opensBeforePreview=opens;
  const preview=await m.command('previewJob',{id:old.id});
  assert.deepEqual(preview.bundle,bundle);assert.deepEqual(preview.accountIds,[a.id]);
  assert.equal(JSON.stringify(m.state),beforePreview,'preview does not mutate task status or usage');
  assert.equal(opens,opensBeforePreview,'preview never opens a browser');
  await assert.rejects(m.command('previewJob',{id:'../missing'}),/任务不存在/);
  const originalCount=m.stats(a).submitted;
  await m.command('pause',{paused:true});
  await assert.rejects(m.command('regenerate',{id:old.id}),/暂停/);assert.equal(m.state.jobs.length,1);
  await m.command('pause',{paused:false});
  await Promise.all([m.command('regenerate',{id:old.id}),m.command('regenerate',{id:old.id})]);
  const retry=m.state.jobs[1];assert.equal(m.state.jobs.length,2);assert.equal(retry.retryOf,old.id);assert.equal(old.retryJobId,retry.id);
  assert.equal(retry.status,'queued');assert.equal(retry.submittedAt,undefined);assert.equal(m.stats(a).submitted,originalCount);
  const copied=JSON.parse(await fs.readFile(path.join(root,`${retry.id}.bundle.json`),'utf8'));assert.deepEqual(copied,bundle);
  a.lastSeen=0;a.lastRetryWake=0;await m.command('wakeQueue');assert(opens>0,'offline original account is opened for idle verification');
  await m.event(a,{type:'runtime',state:'busy'});m.dispatch();assert.equal(retry.status,'queued');
  await m.event(a,{type:'runtime',state:'idle',readyForGeneration:true});m.dispatch();assert.equal(retry.status,'queued','one observation cannot unlock');
  a.runtimeAt-=1100;await m.event(a,{type:'runtime',state:'idle',readyForGeneration:true});assert.equal(old.status,'failed');assert(old.terminalAt);
  await m.event(a,{type:'runtime',state:'idle',readyForGeneration:true});a.runtimeAt-=1100;await m.event(a,{type:'runtime',state:'idle',readyForGeneration:true});
  m.dispatch();assert.equal(retry.status,'prepared');assert.equal(retry.accountId,a.id);
  await m.event(a,{type:'result',jobId:old.id,original:true,requestId:'request',url:'https://test.byteimg.com/old.mp4'});
  assert.equal(old.media,undefined);assert.equal(old.status,'failed','late results cannot replace a retry');
  await assert.rejects(m.command('resume',{id:old.id}),/仅可/);
  console.log('PASS timeout failure, paused rejection, one retry per failed attempt, exact ordered bundle, reconnect, fresh idle gating, no duplicate counts and stale result suppression.');
} finally {await m.stop();}
