import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const { exportVideo } = createRequire(import.meta.url)('./video-files.cjs');
const videosDir = await fs.mkdtemp(path.join(os.tmpdir(), 'director-video-test-'));
const mediaId = '3f2ef4ce-f64e-4965-b773-6c14ab13f6f5';
const input = { projectId: 'project-test', mediaId, name: '分镜/../:CON' };
const chunks = [new Uint8Array([0, 1, 2]), new Uint8Array([3, 4, 5])];
let requests = 0;
const config = { videosDir, origin: 'http://127.0.0.1:32100', token: 'test-only', fetchVideo: async (url, init) => {
  requests++;
  assert.equal(url, `http://127.0.0.1:32100/api/media/${mediaId}`);
  assert.equal(init.headers.Cookie, 'director_session=test-only');
  assert.equal(init.redirect, 'error');
  return new Response(new ReadableStream({ start(c) { for (const chunk of chunks) c.enqueue(chunk); c.close(); } }), { headers: { 'content-type': 'video/mp4' } });
} };
const filename = await exportVideo(input, config);
const folder = path.join(videosDir, 'AI短片导演', input.projectId);
assert(filename.startsWith(folder + path.sep));
assert.equal(path.extname(filename), '.mp4');
assert.deepEqual(await fs.readFile(filename), Buffer.from([0, 1, 2, 3, 4, 5]));
await fs.writeFile(filename, 'user-edited-video');
await exportVideo(input, config);
assert.equal(await fs.readFile(filename, 'utf8'), 'user-edited-video');
const before = requests;
await assert.rejects(exportVideo({ ...input, projectId: '../other' }, config), /无效/);
await assert.rejects(exportVideo({ ...input, mediaId: 'https://evil.example' }, config), /无效/);
assert.equal(requests, before);
await assert.rejects(exportVideo(input, { ...config, fetchVideo: async () => new Response('missing', { status: 404 }) }), /无法读取/);
await assert.rejects(exportVideo(input, { ...config, fetchVideo: async () => new Response('html', { headers: { 'content-type': 'text/html' } }) }), /不是支持/);
await assert.rejects(exportVideo({ ...input, name: 'empty' }, { ...config, fetchVideo: async () => new Response('', { headers: { 'content-type': 'video/mp4' } }) }), /内容为空/);
let sent = false;
await assert.rejects(exportVideo({ ...input, name: 'broken' }, { ...config, fetchVideo: async () => new Response(new ReadableStream({ pull(c) { if (sent) c.error(Error('connection lost')); else { sent = true; c.enqueue(chunks[0]); } } }), { headers: { 'content-type': 'video/mp4' } }) }), /connection lost/);
assert.deepEqual(await fs.readdir(folder), [path.basename(filename)]);
console.log('PASS: local video stream export, authenticated same-origin request, safe paths, preserved existing copy, MIME/errors/empty/interrupted streams, no leftover partial files.');
