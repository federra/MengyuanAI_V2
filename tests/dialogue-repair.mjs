// Run after tests/core.mjs. These cases cover the supplied import syntax and saved legacy rows.
import assert from 'node:assert/strict';
import {parseAudioLines,dialogueLines,dialogueText} from '../work/test/dialogue.mjs';
import {parseShots,exportStoryboard} from '../work/test/director.mjs';
import {newProject} from '../work/test/studio.mjs';
const audio='石头 ( @role_shitou ) （音色：清亮稚嫩男童音）发出对白：【期待】“妈，今天一定要回来呀。”；音效：红笔摩擦纸张；窗外鸟鸣';
const parsed=parseAudioLines(audio,['石头']);
assert.equal(parsed.length,1);
assert.equal(parsed[0].speaker,'石头');
assert.equal(parsed[0].emotion,'期待');
assert.equal(parsed[0].text,'妈，今天一定要回来呀。');
assert.equal(parsed[0].voiceName,'','a voice description is not a saved voice asset');
const two=parseAudioLines('美女徒弟（恐惧）：师傅！这雨也太大了。\n师傅（平静）：雨刮不是救命按钮。',['师傅','美女徒弟']);
assert.deepEqual(two.map(l=>[l.speaker,l.emotion]),[['美女徒弟','恐惧'],['师傅','平静']]);
assert.equal(parseAudioLines('石头：“妈妈！” 妈妈：“石头！”',['石头','妈妈']).length,2);
assert.equal(parseAudioLines('师傅：他说“等一下”，那我们（先）别走。',['师傅'])[0].text,'他说“等一下”，那我们（先）别走。');
assert.equal(parseAudioLines('0—5秒：画笔摩擦纸张声，清晨的鸟鸣声\n5—12秒：',['石头']).length,0);
assert.equal(parseAudioLines('谁在门外？',['石头','妈妈'])[0].speaker,'','do not invent a speaker');
const narration=parseAudioLines('旁白：“新的一天开始了。”',['石头'])[0];
assert.equal(narration.kind,'旁白');
const legacy={id:'old',character:'石头',dialogue:'0—5秒：'+audio,lines:[]};
assert.equal(dialogueLines(legacy)[0].speaker,'石头');
const manual={...legacy,lines:[{...parsed[0],speaker:'妈妈'}],dialogue:parsed[0].text};
assert.equal(dialogueLines(manual)[0].speaker,'妈妈','preserve manual speaker assignments');
const project=newProject();
project.shots=parseShots(JSON.stringify({shots:[{title:'对白测试',description:'双人对话',character:'美女徒弟、师傅',dialogue:dialogueText(two),lines:two}]}));
const restored=parseShots(JSON.stringify(exportStoryboard(project)));
assert.deepEqual(restored[0].lines.map(l=>[l.kind,l.speaker,l.emotion,l.text]),two.map(l=>[l.kind,l.speaker,l.emotion,l.text]));
console.log('PASS role/emotion extraction, sound-only rows, narration, ambiguous speakers, legacy recovery and edited dialogue round-trip.');
