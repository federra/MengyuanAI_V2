import assert from 'node:assert/strict';
import {probeResult} from '../browser-extension/probe-result.js';
const url='https://www.doubao.com/chat/123456';
globalThis.location={origin:'https://www.doubao.com',pathname:'/chat/123456',href:url};
let clicks=0,messages=[];
const control=()=>({getClientRects:()=>[1],closest:()=>null,contains:()=>false,click:()=>clicks++});
const message=(id,text,controls=[],streaming=false)=>({innerText:text,getClientRects:()=>[1],closest:()=>null,getAttribute:()=>id,querySelector:()=>streaming?{}:null,querySelectorAll:()=>controls});
globalThis.document={querySelectorAll:()=>messages};
const prompt='原始分镜提示词用于精确匹配本次任务和对应的参考图片';
const progress='本次使用 Seedance 2.0 Mini 生成，预计等待 5 分钟。视频生成好后，我会主动发送给你。';
const job={requestId:'req',generationAcceptedAt:1,conversationUrl:url,progressMessage:progress,task:{prompt}};
messages=[message('waiting',progress),message('result','你的视频生成好了。',[control()])];
assert.equal(probeResult(job).messageId,'result','stored progress associates result when prompt is virtualized');
assert.equal(clicks,0,'inspection alone cannot click');probeResult(job,true);assert.equal(clicks,1);
assert.equal(probeResult({...job,conversationUrl:'https://www.doubao.com/chat/999'}),null);
assert.equal(probeResult({...job,requestId:null}),null);
assert.equal(probeResult({...job,progressMessage:'different'}),null);
assert.equal(probeResult({...job,progressMessage:'',generationMessageId:'waiting'}).messageId,'result');
messages.splice(1,0,message('unrelated','请生成另一条视频'));assert.equal(probeResult(job),null,'intervening conversation cannot be attributed by progress fallback');
messages=[message('prompt',prompt),message('result','你的视频生成好了。',[control()])];
assert.equal(probeResult({task:{prompt}}).messageId,'result','original prompt association remains supported');
messages[1]=message('result','你的视频生成好了。',[control(),control()]);assert.equal(probeResult(job),null,'ambiguous videos require reconciliation');
messages[1]=message('result','你的视频生成好了。',[control()],true);assert.equal(probeResult(job),null);
messages=[message('unrelated','你的视频生成好了。',[control()])];assert.equal(probeResult(job),null);
delete globalThis.location;delete globalThis.document;
console.log('PASS result probe: virtualized prompt, persisted progress/id, exact conversation, no inspection click, ambiguity and streaming.');
