import assert from 'node:assert/strict';
const newShot = () => ({enabled:true,trimStart:0});
const newProject = title => ({title,brief:'',story:'',script:'',scenes:'',shots:[],assets:[]});
import { projectOverview } from '../lib/project-overview.ts';
const image = { id: 'image', name: 'image', type: 'image/png', url: '/api/media/image' };
const video = { id: 'video', name: 'video', type: 'video/mp4', url: '/api/media/video' };
const p = newProject('状态测试');
assert.equal(projectOverview(p).status, 'empty');
p.brief = '一个创意'; assert.equal(projectOverview(p).status, 'idea');
p.storyPlans = [{id:'story', title:'候选故事', summary:'', content:'正文', tags:[]}];
assert.equal(projectOverview(p).status, 'story');
p.script = '剧本'; assert.equal(projectOverview(p).status, 'script');
p.shots = [newShot(), newShot()];
assert.equal(projectOverview(p).status, 'storyboard');
p.shots[0].image = image;
assert.equal(projectOverview(p).status, 'assets', '部分镜头有画面不能显示画面齐备');
p.shots[1].video = video; p.shots[1].trimStart = 2;
assert.equal(projectOverview(p).status, 'ready');
assert.deepEqual(projectOverview(p).covers[0], {kind:'video',url:video.url,time:2});
assert.equal(projectOverview(p).covers[1].url,image.url,'视频封面失败后仍有图片候选');
p.shots[0].enabled = false; delete p.shots[1].video;
assert.notEqual(projectOverview(p).status,'ready','停用镜头素材不能令缺画面的启用镜头就绪');
p.shots[1].firstFrame = image;
assert.notEqual(projectOverview(p).status,'ready','参考首帧不是镜头成片');
p.shots = [];
p.assets = [{id:'a',kind:'人物',name:'角色',description:'',image,referenceImage:image}];
assert.equal(projectOverview(p).status,'assets');
p.assets[0].dismissedImageId=image.id;
assert.equal(projectOverview(p).covers.length,0,'已清除的图片和生成参考图不作为项目封面');
p.assets[0].dismissedImageId=undefined;
p.assets.push({...p.assets[0],id:'b'});
assert.equal(projectOverview(p).covers.length,1,'重复素材只尝试加载一次');
console.log('PASS project progress, enabled shots, cover priority, fallback candidates and dismissed images');
