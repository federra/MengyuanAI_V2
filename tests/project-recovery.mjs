import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
import vm from 'node:vm';
const source=await fs.readFile('lib/project-recovery.ts','utf8');
const code=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const ctx={exports:{},crypto:{randomUUID:()=> 'recovered-id'}};vm.createContext(ctx);vm.runInContext(code,ctx);
const {recoverProject}=ctx.exports;
const draft={id:'p',revision:1,title:'test',updatedAt:'old',brief:'draft',shots:[],assets:[]};
const saved={...draft,revision:2,brief:'saved',updatedAt:'new'};
const result=recoverProject(draft,[saved]);
assert.equal(result.project.id,'recovered-id');assert.equal(result.project.revision,0);
assert.equal(result.project.brief,'draft');assert.equal(saved.brief,'saved');assert.equal(draft.id,'p');assert(result.copied);
const same=recoverProject({...saved,revision:1,updatedAt:'old'},[saved]);
assert.equal(same.project,saved);assert.equal(same.dirty,false);
const normal=recoverProject(draft,[{...saved,revision:1}]);assert.equal(normal.project,draft);assert(normal.dirty);
assert.equal(recoverProject(draft,[]).project.revision,0);
assert.equal(recoverProject({...draft,revision:0},[]).copied,false);
console.log('PASS stale drafts kept as separate copies; equal content uses saved revision; current drafts retained; missing saved projects recover safely');
