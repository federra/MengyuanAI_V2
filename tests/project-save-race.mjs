import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
import vm from 'node:vm';
const source=await fs.readFile('app/page.tsx','utf8');
const code=source.slice(source.indexOf('  async function save('),source.indexOf('  async function action('));
let revision=1;
const current={current:{id:'p',revision:1,title:'original'}}, isDirty={current:true};
const states=[];
const context={recoveryCopies:{current:new Set()},current,isDirty,saveQueue:{current:Promise.resolve()},setProjects(){},setProject(p){states.push(p)},setDirty(){},setSavedTime(){},setNotice(){},api:async(url,opts)=>{const p=JSON.parse(opts.body);await new Promise(r=>setTimeout(r,5));if(p.revision!==revision)throw Error('409 stale revision');return {...p,revision:++revision,updatedAt:'now'};}};
vm.createContext(context);vm.runInContext(ts.transpileModule(code,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText,context);
const results=await Promise.allSettled([context.save(),context.save()]);
assert(results.every(r=>r.status==='fulfilled'),'overlapping saves must use latest acknowledged revision');
assert.equal(current.current.revision,3,'revision must update before React renders');
console.log('PASS overlapping saves and synchronous revision update');
const saving=context.save();
await new Promise(r=>setTimeout(r,1));
current.current={...current.current,title:'edited while saving'};
await saving;
assert.equal(current.current.title,'edited while saving');
assert.equal(current.current.revision,4);
assert.equal(isDirty.current,true);
revision=5; // A real external writer must still cause a conflict, never force overwrite.
await assert.rejects(context.save(),/409/);
assert.equal(current.current.revision,4);
current.current={...current.current,revision:5};
await context.save();
assert.equal(current.current.revision,6,'failed save must not poison the queue');
console.log('PASS edits during save, real external conflicts and recovery after failure');
