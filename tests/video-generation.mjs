import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const dir = 'work/video-generation-test';
await fs.mkdir(dir, { recursive: true });
for (const name of ['studio', 'dialogue', 'dialogue-timeline', 'video-generation']) {
  const code = ts.transpileModule(await fs.readFile(`lib/${name}.ts`, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText.replace(/from '(\.\/[^']+)'/g,"from '$1.mjs'");
  await fs.writeFile(`${dir}/${name}.mjs`, code);
}
const imp = name => import(pathToFileURL(path.resolve(dir, name + '.mjs')));
const { newProject, newShot, validateProject } = await imp('studio');
const { latestVideoJob, videoJobActive, receiveGeneratedVideos, mergeGenerationJob, VideoJobMonitor, manualVideoPatch } = await imp('video-generation');
const p = newProject('视频回填'); p.shots = [newShot(), newShot()];
const j = { id: 'task-a', projectId: p.id, targetId: p.shots[0].id, target: 'video', status: 'running', createdAt: '2026-09-11T00:00:00Z' };
const {selectedVideoActive}=await imp('video-generation');
assert.equal(selectedVideoActive('doubao',j,{status:'cancelled'}),false,'cancelled Doubao cannot spin because an API job is active');
assert.equal(selectedVideoActive('minimax',{...j,status:'cancelled'},{status:'submitted'}),false,'old Doubao job cannot lock another channel');
assert.equal(selectedVideoActive('doubao',j,{status:'attention'}),false);
assert.equal(selectedVideoActive('doubao',undefined,{status:'submitted'}),true);
assert.equal(selectedVideoActive('minimax',j,{status:'cancelled'}),true);
const media = { id: 'video-a', type: 'video/mp4', url: '/api/media/video-a', name: 'a.mp4' };
const done = { ...j, status: 'succeeded', media };
assert(videoJobActive(j)); assert(videoJobActive({ ...j, status: 'downloading' })); assert(!videoJobActive(done));
const pending = receiveGeneratedVideos(p, [j], new Set());
assert.equal(pending.shots[0].videoPendingJobId, j.id);
assert.equal(pending.shots[1], p.shots[1]);
const applied = receiveGeneratedVideos(pending, [done], new Set());
assert.equal(applied.shots[0].video, media); assert.equal(applied.shots[0].videoGenerationId, j.id);
assert.equal(applied.shots[0].trimStart, 0);
assert.equal(receiveGeneratedVideos(applied, [done], new Set()), applied);
const cleared = { ...applied, shots: applied.shots.map(s => ({ ...s, video: undefined })) };
assert.equal(receiveGeneratedVideos(cleared, [done], new Set()), cleared);
const manual = { ...p, shots: p.shots.map(s => ({ ...s, video: { ...media, id: 'manual' } })) };
assert.equal(receiveGeneratedVideos(manual, [done], new Set()), manual);
assert.equal(receiveGeneratedVideos(manual, [done], new Set([j.id])).shots[0].video.id, media.id);
const manualTime='2026-09-11T00:00:30.000Z';
const replaced={...pending,shots:pending.shots.map((s,i)=>i? s:{...s,...manualVideoPatch({...media,id:'uploaded-video'},manualTime)})};
assert.equal(receiveGeneratedVideos(replaced,[done],new Set([j.id])),replaced,'late live generation cannot overwrite uploaded video');
assert.equal(receiveGeneratedVideos(replaced,[j],new Set([j.id])),replaced,'pending flag is not reattached after manual replacement');
const deleted={...replaced,shots:replaced.shots.map((s,i)=>i?s:{...s,...manualVideoPatch(undefined,manualTime)})};
assert.equal(deleted.shots[0].video,undefined);
const restored=JSON.parse(JSON.stringify(deleted));
assert.equal(receiveGeneratedVideos(restored,[done],new Set([j.id])),restored,'deletion remains after reload');
assert.equal(deleted.shots[0].description,p.shots[0].description);
assert.equal(deleted.shots[1],p.shots[1]);
const future={...j,id:'new-after-manual',createdAt:'2026-09-11T00:00:40.000Z'};
const futurePending=receiveGeneratedVideos(deleted,[future],new Set());
assert.equal(receiveGeneratedVideos(futurePending,[{...future,status:'succeeded',media}],new Set()).shots[0].video.id,media.id,'new generations still apply');
assert.equal(receiveGeneratedVideos(p, [{ ...done, projectId: 'other' }], new Set([j.id])), p);
assert.equal(receiveGeneratedVideos(p, [{ ...done, media: { ...media, type: 'image/png' } }], new Set([j.id])), p);
const newer = { ...j, id: 'newer', createdAt: '2026-09-11T00:01:00Z' };
assert.equal(latestVideoJob([newer, done], p.id, j.targetId), newer);
assert(!receiveGeneratedVideos(p, [newer, done], new Set([done.id])).shots[0].video);
assert.equal(mergeGenerationJob([done], j)[0], done);
const list = Array.from({ length: 5 }, (_, i) => ({ ...j, id: 'job-' + i, projectId: i % 2 ? 'other-project' : p.id }));
const monitor = new VideoJobMonitor(); const calls = []; const releases = []; const records = [];
const refresh = id => { calls.push(id); return new Promise(resolve => releases.push(() => resolve({ ...j, id, status: 'succeeded', media }))); };
const first = monitor.tick(list, refresh, job => records.push(job));
assert.equal(calls.length, 3);
await monitor.tick(list, refresh, job => records.push(job));
assert.equal(calls.length, 3, 'in-flight queries must not duplicate');
releases.splice(0).forEach(resolve => resolve()); await first;
const second = monitor.tick(list, refresh, job => records.push(job));
assert.equal(calls.length, 5, 'other projects continue in the global queue');
releases.splice(0).forEach(resolve => resolve()); await second; assert.equal(records.length, 5);
const retry = new VideoJobMonitor(); let attempts = 0;
const failing = async () => { attempts++; throw Error('temporary network failure'); };
await retry.tick([j], failing, () => assert.fail('failed queries cannot fabricate results'));
await retry.tick([j], failing, () => {}); assert.equal(attempts, 1);
await retry.tick([j], async () => { attempts++; return done; }, job => assert.equal(job, done), Date.now() + 65000);
assert.equal(attempts, 2);
await retry.tick([{ ...j, status: 'submitting' }, { ...j, id: 'failed', status: 'failed' }], failing, () => {});
assert.equal(attempts, 2, 'uncertain submissions and failures are not resubmitted');
console.log('PASS video binding, manual preservation, project isolation, latest task, stale response protection, bounded polling and network retry.');
